snap = json.load(open('data/snapshot/current.json', encoding='utf-8'))
codes = set()
derived = collections.defaultdict(collections.Counter)
for r in snap['records']:
    z = [c.strip() for c in str(r.get('zipCd', '')).split(',') if c.strip()]
    codes.update(z)
    if len(z) == 1:
        for org in (r.get('sprvsnInstCdNm', ''), r.get('rgtrHghrkInstCdNm', '')):
            for t in re.findall(r'([가-힣]+(?:시|군|구))(?![가-힣])', org or ''):
                if not t.endswith(('광역시', '특별시', '자치시')):
                    derived[z[0]][t] += 1

labels = {}
for c in sorted(codes):
    sido = SIDO.get(c[:2], c[:2])
    if c in STD:
        labels[c] = f'{sido} {STD[c]}'
    elif derived[c]:
        labels[c] = f'{sido} {derived[c].most_common(1)[0][0]}'
    else:
        labels[c] = f'{sido} ({c})'

json.dump({
    'source': '행정표준 시군구 코드 이름(내부 작성, 공식 대응표와 대조 전). 전남광주통합특별시(12)는 스냅샷의 주관·등록기관명에서 역산.',
    'labels': labels,
}, open('data/regions.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
missing = [c for c, v in labels.items() if v.endswith(')') and '구(' not in v]
print(len(labels), 'unlabeled:', missing)
